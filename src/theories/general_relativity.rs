use std::f64::consts::PI;
use crate::dimensions::{Dimension, Quantity};
use crate::empirical::Context;
use crate::theory::{Principle, Symmetry, Theory, TheoryError};

pub const DEFAULT_G: f64 = 6.67430e-11;
pub const DEFAULT_C: f64 = 299792458.0;

pub struct GeneralRelativity {
    pub g: f64,
    pub c: f64,
}

impl GeneralRelativity {
    pub fn new() -> Self {
        Self {
            g: DEFAULT_G,
            c: DEFAULT_C,
        }
    }

    pub fn with_constants(g: f64, c: f64) -> Self {
        Self { g, c }
    }
}

impl Default for GeneralRelativity {
    fn default() -> Self {
        Self::new()
    }
}

impl Theory for GeneralRelativity {
    fn id(&self) -> &str {
        "general_relativity"
    }

    fn name(&self) -> &str {
        "Einstein's General Relativity (Curved Spacetime)"
    }

    fn principles(&self) -> Vec<Principle> {
        vec![
            Principle {
                name: "Principle of Equivalence".to_string(),
                description: "Inertial and gravitational masses are identical; local effects of gravity are indistinguishable from uniform acceleration."
                    .to_string(),
            },
            Principle {
                name: "General Covariance".to_string(),
                description: "The laws of physics must take the same tensor form in all coordinate systems."
                    .to_string(),
            },
            Principle {
                name: "Einstein Field Equations".to_string(),
                description: "G_mu_nu + Lambda*g_mu_nu = (8*pi*G / c^4) * T_mu_nu, describing spacetime curvature generated by matter-energy."
                    .to_string(),
            },
            Principle {
                name: "Geodesic Motion".to_string(),
                description: "Freely falling particles follow timelike or null geodesics of the spacetime metric."
                    .to_string(),
            },
        ]
    }

    fn symmetries(&self) -> Vec<Symmetry> {
        vec![
            Symmetry::new("Diffeomorphism Invariance", "Diff(M)", "Energy-Momentum Conservation (via contracted Bianchi identity)"),
            Symmetry::time_translation(),
            Symmetry::rotation_so3(),
        ]
    }

    fn is_in_regime(&self, phenomenon_id: &str, _context: &Context) -> Result<(), TheoryError> {
        // Classical General Relativity applies to gravitational and spacetime phenomena;
        // microscopic quantum transitions and statistical thermodynamics are outside its domain.
        if phenomenon_id.starts_with("quantum:") || phenomenon_id.starts_with("thermo:") {
            return Err(TheoryError::OutsideDomain(
                phenomenon_id.to_string(),
                self.id().to_string(),
            ));
        }
        Ok(())
    }

    fn predict(&self, phenomenon_id: &str, context: &Context) -> Result<Quantity, TheoryError> {
        match phenomenon_id {
            "gravitational_constant:codata2018" => {
                Ok(Quantity::gravitational_constant(self.g))
            }
            "kepler:earth_orbital_period" => {
                // In weak-field limit, GR reproduces Kepler's Third Law with tiny Post-Newtonian correction
                let a = context
                    .get_required("semi_major_axis")
                    .map_err(TheoryError::MissingParameter)?;
                a.check_dimension(Dimension::length())?;

                let m_central = context
                    .get_required("central_mass")
                    .map_err(TheoryError::MissingParameter)?;
                m_central.check_dimension(Dimension::mass())?;

                let m_orbiting = context
                    .get("orbiting_mass")
                    .copied()
                    .unwrap_or_else(|| Quantity::mass(0.0));

                let total_mass = m_central.value + m_orbiting.value;
                let a_cubed = a.value.powi(3);
                let denominator = self.g * total_mass;
                let t_newton = 2.0 * PI * (a_cubed / denominator).sqrt();
                // 1PN fractional correction is of order GM / (a * c^2) ~ 1e-8
                let pn_correction = 1.0 + (self.g * total_mass) / (a.value * self.c * self.c);
                Ok(Quantity::time(t_newton * pn_correction))
            }
            "gr:mercury_perihelion_excess" => {
                // GR Precession: Delta phi = 6 * pi * G * M / (c^2 * a * (1 - e^2)) radians per orbit
                let m = context
                    .get_required("central_mass")
                    .map_err(TheoryError::MissingParameter)?;
                let a = context
                    .get_required("semi_major_axis")
                    .map_err(TheoryError::MissingParameter)?;
                let e = context
                    .get_required("eccentricity")
                    .map_err(TheoryError::MissingParameter)?;
                let period = context
                    .get_required("orbital_period")
                    .map_err(TheoryError::MissingParameter)?;

                let e_val = e.value;
                let delta_phi_rad = (6.0 * PI * self.g * m.value)
                    / (self.c * self.c * a.value * (1.0 - e_val * e_val));

                // Convert from radians per orbit to arcseconds per century
                // 1 Julian century = 36525 days = 36525 * 86400 seconds
                let century_seconds = 36525.0 * 86400.0;
                let orbits_per_century = century_seconds / period.value;
                let rad_to_arcsec = 180.0 * 3600.0 / PI;

                let precession_arcsec_per_century = delta_phi_rad * orbits_per_century * rad_to_arcsec;
                Ok(Quantity::dimensionless(precession_arcsec_per_century))
            }
            "relativity:muon_dilated_lifetime" => {
                // In flat-spacetime limit, GR reduces to Special Relativity
                let tau_0 = context
                    .get_required("rest_lifetime")
                    .map_err(TheoryError::MissingParameter)?;
                let v = context
                    .get_required("velocity")
                    .map_err(TheoryError::MissingParameter)?;

                let beta = v.value / self.c;
                let gamma = 1.0 / (1.0 - beta * beta).sqrt();
                Ok(Quantity::time(gamma * tau_0.value))
            }
            "relativity:electron_momentum_at_0.8c" => {
                let m0 = context
                    .get_required("rest_mass")
                    .map_err(TheoryError::MissingParameter)?;
                let v = context
                    .get_required("velocity")
                    .map_err(TheoryError::MissingParameter)?;

                let beta = v.value / self.c;
                let gamma = 1.0 / (1.0 - beta * beta).sqrt();
                Ok(Quantity::momentum(gamma * m0.value * v.value))
            }
            "em:maxwell_wave_speed" => {
                let eps = context
                    .get("permittivity")
                    .map(|q| q.value)
                    .unwrap_or(8.8541878128e-12);
                let mu = context
                    .get("permeability")
                    .map(|q| q.value)
                    .unwrap_or(1.25663706212e-6);
                let c = 1.0 / (eps * mu).sqrt();
                Ok(Quantity::velocity(c))
            }
            "em:coulomb_force" => {
                let q1 = context
                    .get_required("charge1")
                    .map_err(TheoryError::MissingParameter)?;
                q1.check_dimension(Dimension::charge())?;
                let q2 = context
                    .get_required("charge2")
                    .map_err(TheoryError::MissingParameter)?;
                q2.check_dimension(Dimension::charge())?;
                let r = context
                    .get_required("separation")
                    .map_err(TheoryError::MissingParameter)?;
                r.check_dimension(Dimension::length())?;
                let eps0 = 8.8541878128e-12;
                let force_val = (q1.value * q2.value) / (4.0 * PI * eps0 * r.value * r.value);
                Ok(Quantity::force(force_val))
            }
            _ => Err(TheoryError::OutsideDomain(
                phenomenon_id.to_string(),
                self.id().to_string(),
            )),
        }
    }
}
